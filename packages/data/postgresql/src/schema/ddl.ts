import {literalOf, quote} from "@spica-server/data-postgresql-orm";
import {BucketDiff} from "@spica-server/bucket-common";
import {BucketSchemaError, constraintName} from "./naming.js";
import {BucketMetadata, ColumnMetadata, IndexMetadata} from "./metadata.js";

function generationSql(metadata: BucketMetadata) {
  const {generated, type} = metadata.primaryKey;
  if (!generated) {
    return "";
  }
  return type == "uuid" ? " DEFAULT uuidv7()" : " GENERATED BY DEFAULT AS IDENTITY";
}

function columnSql(metadata: BucketMetadata, column: ColumnMetadata) {
  const isKey = column.name == metadata.primaryKey.column;
  return [
    quote(column.name),
    column.type,
    column.notNull ? "NOT NULL" : "",
    isKey ? generationSql(metadata).trim() : ""
  ]
    .filter(Boolean)
    .join(" ");
}

function checkSql(table: string, column: ColumnMetadata) {
  const values = column.enum.filter(value => value !== null).map(literalOf);
  return `ALTER TABLE ${quote(table)} ADD CONSTRAINT ${quote(column.checkName)} CHECK (${quote(column.name)} IN (${values.join(", ")}))`;
}

function createIndexSql(table: string, index: IndexMetadata) {
  const columns = index.columns.map(column => `${quote(column.name)} ${column.order}`);
  return `CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${quote(index.name)} ON ${quote(table)} (${columns.join(", ")})`;
}

export function createStatements(metadata: BucketMetadata): string[] {
  const {main, primaryKey} = metadata;
  const columns = main.columns.map(column => `  ${columnSql(metadata, column)}`);
  const primary = `  CONSTRAINT ${quote(constraintName(main.name, [primaryKey.column], "pk"))} PRIMARY KEY (${quote(primaryKey.column)})`;

  return [
    `CREATE TABLE ${quote(main.name)} (\n${[...columns, primary].join(",\n")}\n)`,
    ...main.columns.filter(column => column.enum).map(column => checkSql(main.name, column)),
    ...main.indexes.map(index => createIndexSql(main.name, index))
  ];
}

function assertSameKey(previous: BucketMetadata, next: BucketMetadata) {
  const before = previous.primaryKey;
  const after = next.primaryKey;
  if (
    before.field != after.field ||
    before.type != after.type ||
    before.generated != after.generated
  ) {
    throw new BucketSchemaError(["Changing the primary key is not supported yet."]);
  }
}

export function updateStatements(
  previous: BucketMetadata,
  next: BucketMetadata,
  diff: BucketDiff
): string[] {
  assertSameKey(previous, next);

  const table = quote(next.main.name);
  const alter = (action: string) => `ALTER TABLE ${table} ${action}`;

  const dropIndexes: string[] = [];
  const dropChecks: string[] = [];
  const dropColumns: string[] = [];
  const addColumns: string[] = [];
  const alterColumns: string[] = [];
  const addChecks: string[] = [];
  const createIndexes: string[] = [];

  for (const change of diff.indexes) {
    if (change.kind == "removed") {
      dropIndexes.push(`DROP INDEX IF EXISTS ${quote(previous.indexOf(change.index).name)}`);
    } else {
      createIndexes.push(createIndexSql(next.main.name, next.indexOf(change.index)));
    }
  }

  const retyped: string[] = [];

  for (const change of diff.fields) {
    const before = previous.columnOf(change.path);
    const after = next.columnOf(change.path);

    switch (change.kind) {
      case "removed":
        dropColumns.push(alter(`DROP COLUMN ${quote(before.name)}`));
        break;
      case "added":
        addColumns.push(alter(`ADD COLUMN ${columnSql(next, after)}`));
        if (after.enum) {
          addChecks.push(checkSql(next.main.name, after));
        }
        break;
      case "retyped":
        if (before.type != after.type) {
          retyped.push(change.path.join("."));
        }
        break;
      case "required":
        if (before.notNull != after.notNull) {
          alterColumns.push(
            alter(`ALTER COLUMN ${quote(after.name)} ${after.notNull ? "SET" : "DROP"} NOT NULL`)
          );
        }
        break;
      case "enum":
        if (before.checkName) {
          dropChecks.push(alter(`DROP CONSTRAINT ${quote(before.checkName)}`));
        }
        if (after.enum) {
          addChecks.push(checkSql(next.main.name, after));
        }
        break;
    }
  }

  if (retyped.length) {
    throw new BucketSchemaError([
      `Changing the type of a property is not supported yet: ${retyped.join(", ")}.`
    ]);
  }

  return [
    ...dropIndexes,
    ...dropChecks,
    ...dropColumns,
    ...addColumns,
    ...alterColumns,
    ...addChecks,
    ...createIndexes
  ];
}
