import {literalOf, quote} from "@spica-server/data-postgresql-orm";
import {constraintName} from "../naming.js";
import {
  BucketMetadata,
  ColumnMetadata,
  ForeignKeyMetadata,
  IndexMetadata,
  TableMetadata
} from "../metadata/index.js";

export const alterTable = (table: string, action: string) =>
  `ALTER TABLE ${quote(table)} ${action}`;

export const alterColumn = (table: string, column: string, action: string) =>
  alterTable(table, `ALTER COLUMN ${quote(column)} ${action}`);

export const dropColumnSql = (table: string, column: string) =>
  alterTable(table, `DROP COLUMN ${quote(column)}`);

export const dropConstraintSql = (table: string, constraint: string, ifExists = false) =>
  alterTable(table, `DROP CONSTRAINT ${ifExists ? "IF EXISTS " : ""}${quote(constraint)}`);

export const dropIndexSql = (index: string) => `DROP INDEX IF EXISTS ${quote(index)}`;

export const dropTablesStatements = (tables: string[]) =>
  tables.map(table => `DROP TABLE ${quote(table)} CASCADE`);

export function generationSql(metadata: BucketMetadata) {
  const {generated, type} = metadata.primaryKey;
  if (!generated) {
    return "";
  }
  return type == "uuid" ? "DEFAULT uuidv7()" : "GENERATED BY DEFAULT AS IDENTITY";
}

export function columnSql(metadata: BucketMetadata, table: TableMetadata, column: ColumnMetadata) {
  const isKey = table == metadata.main && column.name == metadata.primaryKey.column;
  return [
    quote(column.name),
    column.type,
    column.notNull ? "NOT NULL" : "",
    isKey ? generationSql(metadata) : ""
  ]
    .filter(Boolean)
    .join(" ");
}

export const addColumnSql = (
  metadata: BucketMetadata,
  table: TableMetadata,
  column: ColumnMetadata
) => alterTable(table.name, `ADD COLUMN ${columnSql(metadata, table, column)}`);

export function checkSql(table: string, column: ColumnMetadata) {
  const values = column.enum.filter(value => value !== null).map(literalOf);
  return alterTable(
    table,
    `ADD CONSTRAINT ${quote(column.checkName)} CHECK (${quote(column.name)} IN (${values.join(", ")}))`
  );
}

export function createIndexSql(index: IndexMetadata) {
  const columns = index.columns.map(column =>
    index.method == "gist" ? quote(column.name) : `${quote(column.name)} ${column.order}`
  );
  return `CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${quote(index.name)} ON ${quote(index.table)} USING ${index.method} (${columns.join(", ")})`;
}

export function foreignKeySql(key: ForeignKeyMetadata) {
  const onDelete = key.onDelete == "RESTRICT" ? "" : ` ON DELETE ${key.onDelete}`;
  return `CONSTRAINT ${quote(key.name)} FOREIGN KEY (${quote(key.column)}) REFERENCES ${quote(key.table)} (${quote(key.referencedColumn)})${onDelete}`;
}

export const addForeignKeySql = (table: string, key: ForeignKeyMetadata) =>
  alterTable(table, `ADD ${foreignKeySql(key)}`);

export const addPrimaryKeySql = (table: string, column: string) =>
  alterTable(
    table,
    `ADD CONSTRAINT ${quote(constraintName(table, [column], "pk"))} PRIMARY KEY (${quote(column)})`
  );

export function createTableSql(
  metadata: BucketMetadata,
  table: TableMetadata,
  withForeignKeys: boolean
) {
  const definitions = [
    ...table.columns.map(column => columnSql(metadata, table, column)),
    `CONSTRAINT ${quote(constraintName(table.name, table.keyColumns, "pk"))} PRIMARY KEY (${table.keyColumns.map(quote).join(", ")})`,
    ...(withForeignKeys ? table.foreignKeys.map(foreignKeySql) : [])
  ];
  return `CREATE TABLE ${quote(table.name)} (\n${definitions.map(definition => `  ${definition}`).join(",\n")}\n)`;
}
