import {quote} from "@spica-server/data-postgresql-orm";
import {PrimaryKeyMetadata} from "../primary-key.js";
import {alterColumn} from "./sql.js";

export function dropGenerationSql(table: string, key: PrimaryKeyMetadata) {
  if (!key.generated) {
    return [];
  }
  const action = key.type == "uuid" ? "DROP DEFAULT" : "DROP IDENTITY IF EXISTS";
  return [alterColumn(table, key.column, action)];
}

export function addGenerationSql(table: string, key: PrimaryKeyMetadata) {
  if (!key.generated) {
    return [];
  }
  if (key.type == "uuid") {
    return [alterColumn(table, key.column, "SET DEFAULT uuidv7()")];
  }
  return [
    alterColumn(table, key.column, "ADD GENERATED BY DEFAULT AS IDENTITY"),
    `SELECT setval(pg_get_serial_sequence('${quote(table)}', '${key.column}'), COALESCE((SELECT MAX(${quote(key.column)}) FROM ${quote(table)}), 0) + 1, false)`
  ];
}

export function backfillSql(table: string, key: PrimaryKeyMetadata) {
  const column = quote(key.column);
  if (key.type == "uuid") {
    return [`UPDATE ${quote(table)} SET ${column} = uuidv7() WHERE ${column} IS NULL`];
  }
  return [
    `UPDATE ${quote(table)} AS target SET ${column} = numbered.position FROM (SELECT ctid AS row_id, COALESCE((SELECT MAX(${column}) FROM ${quote(table)}), 0) + ROW_NUMBER() OVER () AS position FROM ${quote(table)} WHERE ${column} IS NULL) AS numbered WHERE target.ctid = numbered.row_id`
  ];
}
