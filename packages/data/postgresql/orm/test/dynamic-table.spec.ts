import {createPostgresDatabase} from "@spica-server/database-testing";
import pg from "pg";
import {Orm} from "../src/session.js";

describe("DynamicTable", () => {
  let pool: pg.Pool;
  let orm: Orm;

  beforeAll(async () => {
    pool = new pg.Pool({connectionString: await createPostgresDatabase()});
    orm = new Orm(pool);
    await orm.executeStatements([
      `CREATE TABLE "owners" (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text)`,
      `CREATE TABLE "pets" (_parent integer REFERENCES "owners" (id) ON DELETE CASCADE, _position integer, _value text)`
    ]);
  }, 120_000);

  afterAll(() => pool.end());

  beforeEach(() => orm.truncate(["owners"]));

  const owners = () => orm.table("owners");
  const pets = () => orm.table("pets");

  it("should insert a row and return it with its generated columns", async () => {
    expect(await owners().insertRow({name: "ann"})).toEqual({id: expect.any(Number), name: "ann"});
  });

  it("should insert a row that has no values at all", async () => {
    expect(await owners().insertRow({})).toEqual({id: expect.any(Number), name: null});
  });

  it("should insert many rows in one go and return them in order", async () => {
    const {id} = await owners().insertRow({name: "ann"});

    const inserted = await pets().insertRows([
      {_parent: id, _position: 0, _value: "cat"},
      {_parent: id, _position: 1, _value: "dog"}
    ]);

    expect(inserted.map(row => row._value)).toEqual(["cat", "dog"]);
    expect(await pets().insertRows([])).toEqual([]);
  });

  it("should split a large insert into several statements", async () => {
    const {id} = await owners().insertRow({name: "ann"});
    const rows = Array.from({length: 12_000}, (_, position) => ({
      _parent: id,
      _position: position,
      _value: "x"
    }));

    expect(await pets().insertRows(rows)).toHaveLength(12_000);
  });

  it("should update the row of a key and return it", async () => {
    const {id} = await owners().insertRow({name: "ann"});

    expect(await owners().updateRow("id", id, {name: "bob"})).toEqual({id, name: "bob"});
    expect(await owners().updateRow("id", id + 1, {name: "x"})).toBeUndefined();
  });

  it("should lock and return the row of a key", async () => {
    const {id} = await owners().insertRow({name: "ann"});

    expect(await owners().lockRow("id", id)).toEqual({id, name: "ann"});
    expect(await owners().lockRow("id", id + 1)).toBeUndefined();
  });

  it("should read rows ordered by columns, or by a column value", async () => {
    const {id} = await owners().insertRow({name: "ann"});
    await pets().insertRows([
      {_parent: id, _position: 1, _value: "dog"},
      {_parent: id, _position: 0, _value: "cat"}
    ]);

    expect((await pets().rows(["_position"])).map(row => row._value)).toEqual(["cat", "dog"]);
    expect(await pets().rowsWhere("_value", "dog")).toHaveLength(1);
  });

  it("should delete the rows of a value and count them", async () => {
    const {id} = await owners().insertRow({name: "ann"});
    await pets().insertRows([
      {_parent: id, _position: 0, _value: "cat"},
      {_parent: id, _position: 1, _value: "dog"}
    ]);

    expect(await pets().deleteWhere("_value", "cat")).toBe(1);
    expect(await pets().deleteWhereIn("_value", ["dog", "bird"])).toBe(1);
    expect(await pets().rows()).toEqual([]);
  });

  it("should list the smallest values of a column", async () => {
    await owners().insertRows([{name: "c"}, {name: "a"}, {name: "b"}]);

    expect(await owners().smallest("name", 2)).toEqual(["a", "b"]);
  });

  it("should move an identity sequence past a key that was given", async () => {
    await owners().insertRow({id: 50, name: "given"});
    await owners().advanceSequence("id", 50);

    expect((await owners().insertRow({name: "next"})).id).toBe(51);

    await owners().advanceSequence("id", 10);
    expect((await owners().insertRow({name: "later"})).id).toBe(52);
  });

  it("should count the rows of several tables at once", async () => {
    const {id} = await owners().insertRow({name: "ann"});
    await pets().insertRow({_parent: id, _position: 0, _value: "cat"});

    expect(await orm.countRows(["owners", "pets"])).toBe(2);
    expect(await orm.countRows([])).toBe(0);
  });

  it("should truncate tables together with the rows that refer to them", async () => {
    const {id} = await owners().insertRow({name: "ann"});
    await pets().insertRow({_parent: id, _position: 0, _value: "cat"});

    await orm.truncate(["owners"]);

    expect(await pets().rows()).toEqual([]);
  });
});
